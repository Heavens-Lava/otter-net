using Otter.Language;

namespace Otter.Web;

// Several of otterPS's web-compiler passes walk the syntax tree generically,
// property by property (`$node.PSObject.Properties`): which UI resources are
// created at runtime, which names a loop pass owns (D130/D133), whether a
// code sample uses UI. What they find depends on otterPS's node classes -
// their field names and order - so each otter-net node is described here
// as the otterPS node it stands for (Otter.Contract.psm1), field by field.
//
// A node otter-net has but this table does not know (another area's,
// ported later) cannot be walked the way otterPS would, so the whole
// compilation is left to the PowerShell Otter.
static class NodeFields
{
    // True for the objects otterPS's walkers look inside: the contract's
    // classes (nodes, if-branches, layout specs, animation steps ...).
    public static bool IsContractObject(object? value) =>
        value is Node or IfBranch or UiLayoutSpec or UiAnimationStep or ResponsiveRule or HttpOptions or HttpHeaderClause or DbParameter or QueryOrderByItem;

    public static (string Name, object? Value)[] Of(object node) => node switch
    {
        LiteralExpr n => [("Value", n.Value)],
        VariableExpr n => [("Name", n.Name)],
        MathExpr n => [("Left", n.Left), ("Op", n.Op), ("Right", n.Right)],
        ComparisonExpr n => [("Left", n.Left), ("Op", n.Op), ("Right", n.Right)],
        LogicalExpr n => [("Left", n.Left), ("Op", n.Op), ("Right", n.Right)],
        NotExpr n => [("Operand", n.Operand)],
        ContainsExpr n => [("Collection", n.Collection), ("Item", n.Item)],
        TextMatchExpr n => [("Subject", n.Text), ("Match", n.Match), ("Value", n.Part)],
        OfOperationExpr n => [("Operation", n.Operation), ("Subject", n.Subject)],
        MinMaxExpr n => [("IsMax", n.IsMax), ("Left", n.Left), ("Right", n.Right)],
        ClockExpr n => [("Clock", n.Clock)],
        DateFromTextExpr n => [("Source", n.Source), ("Format", n.Format)],
        DateDifferenceExpr n => [("Unit", n.Unit), ("Start", n.Start), ("End", n.End)],
        PropertyAccessExpr n => [("Property", n.Property), ("Target", n.Target)],
        CallExpr n => [("Name", n.Name), ("Arguments", n.Arguments)],
        FileExistsExpr n => [("Path", n.Path)],
        FileLockedExpr n => [("Path", n.Path)],
        XmlFromExpr n => [("Source", n.Source), ("Value", n.Value)],
        XmlSelectExpr n => [("SelectKind", n.Kind), ("Selector", n.Selector), ("Xml", n.Xml)],
        XmlAttributeExpr n => [("Name", n.Name), ("Element", n.Element)],
        XmlTextOfNameInExpr n => [("Name", n.Name), ("Xml", n.Xml)],
        XmlElementExistsExpr n => [("Selector", n.Selector), ("Xml", n.Xml)],
        XmlHasAttributeExpr n => [("Element", n.Element), ("Name", n.Name)],
        XmlToTextExpr n => [("Xml", n.Xml), ("Pretty", n.Pretty)],
        BytesExpr n => [("Op", n.Op), ("Source", n.Source)],
        BytesFromFileExpr n => [("Path", n.Path)],
        SecureRandomBytesExpr n => [("Count", n.Count)],
        CryptoHashExpr n => [("Algorithm", n.Algorithm), ("Data", n.Data)],
        CryptoHmacExpr n => [("Algorithm", n.Algorithm), ("Data", n.Data), ("Key", n.Key)],
        PasswordMatchesExpr n => [("Password", n.Password), ("Hash", n.Hash)],
        SecurelyEqualsExpr n => [("Left", n.Left), ("Right", n.Right)],
        ConsoleInteractiveExpr => [],
        AwaitExpr n => [("Expression", n.Expression)],
        AwaitStmt n => [("Expression", n.Expression)],
        CurrentRouteExpr => [],
        RouteParameterExpr n => [("Name", n.Name)],
        QueryParameterExpr n => [("Name", n.Name)],
        DragContextExpr n => [("Field", n.Field)],

        SayStmt n => [("Parts", n.Parts), ("ColorExpr", n.Color)],
        AssignStmt n => [("Target", n.Target), ("Value", n.Value)],
        ObjectDefStmt n => [("Name", n.Name), ("TypeName", n.TypeName), ("Properties", n.Properties)],
        TypeDefStmt n => [("TypeName", n.TypeName), ("FieldNames", n.FieldNames)],
        AskStmt n => [("Prompt", n.Prompt), ("Name", n.Name), ("Secret", n.Secret)],
        MathIntoStmt n => [("Expression", n.Expression), ("Target", n.Target)],
        AddToStmt n => [("Amount", n.Amount), ("Target", n.Target)],
        RemoveFromStmt n => [("Amount", n.Amount), ("Target", n.Target)],
        IfBranch n => [("Condition", n.Condition), ("Body", n.Body)],
        IfStmt n => [("Branches", n.Branches), ("ElseBody", n.ElseBody)],
        WhileStmt n => [("Condition", n.Condition), ("Body", n.Body)],
        RepeatStmt n => [("Count", n.Count), ("Body", n.Body)],
        CountStmt n => [("VariableName", n.VariableName), ("From", n.From), ("To", n.To), ("Body", n.Body)],
        ForEachStmt n => [("VariableName", n.VariableName), ("Collection", n.Collection), ("Body", n.Body)],
        ListDefStmt n => [("Name", n.Name), ("Items", n.Items)],
        FunctionDefStmt n => [("Name", n.Name), ("Parameters", n.Parameters), ("Body", n.Body)],
        CallStmt n => [("Call", n.Call), ("ResultTarget", n.ResultTarget)],
        TryStmt n => [("Body", n.Body), ("OtherwiseBody", n.OtherwiseBody), ("ErrorTarget", n.ErrorTarget)],
        FailStmt n => [("Message", n.Message)],
        SortStmt n => [("Target", n.Target)],
        ReverseStmt n => [("Target", n.Target)],
        ReplaceStmt n => [("Find", n.Find), ("Replacement", n.Replacement), ("Target", n.Target), ("ResultTarget", n.ResultTarget)],
        SplitStmt n => [("Subject", n.Subject), ("Separator", n.Separator), ("Target", n.Target)],
        JoinStmt n => [("Subject", n.Subject), ("Separator", n.Separator), ("Target", n.Target)],
        FindStmt n => [("ItemName", n.ItemName), ("Collection", n.Collection), ("Condition", n.Condition), ("Target", n.Target)],
        GetKeyStmt n => [("Key", n.Key), ("Target", n.Target), ("ResultTarget", n.ResultTarget)],
        SetKeyStmt n => [("Key", n.Key), ("Value", n.Value), ("Target", n.Target)],
        DateDifferenceStmt n => [("Unit", n.Unit), ("Start", n.Start), ("End", n.End), ("Target", n.Target)],
        DateAdjustStmt n => [("Amount", n.Amount), ("Unit", n.Unit), ("Target", n.Target), ("IsRemoval", n.IsRemoval)],
        FormatDateStmt n => [("Subject", n.Subject), ("Format", n.Format), ("Target", n.Target)],
        DiagnosticStmt n => [("Level", n.Level), ("Parts", n.Parts)],
        ReturnStmt n => [("Value", n.Value)],
        ReadFileStmt n => [("Path", n.Path), ("Target", n.Target)],
        WriteFileStmt n => [("Content", n.Content), ("Path", n.Path), ("Atomic", n.Atomic)],
        AppendFileStmt n => [("Content", n.Content), ("Path", n.Path)],
        TransferStmt { Action: FileAction.ZipFolder } n => [("SourceFolder", n.Source), ("ArchivePath", n.Destination)],
        TransferStmt { Action: FileAction.Unzip } n => [("ArchivePath", n.Source), ("DestinationFolder", n.Destination)],
        TransferStmt n => [("Source", n.Source), ("Destination", n.Destination)],
        DeleteFileStmt n => [("Path", n.Path)],
        DeleteFolderStmt n => [("Path", n.Path)],
        CreateFolderStmt n => [("Path", n.Path)],
        GetEntriesStmt n => [("Folder", n.Folder), ("IncludeSubfolders", n.IncludeSubfolders), ("Target", n.Target)],
        GetEnvironmentVariableStmt n => [("Name", n.Name), ("Target", n.Target)],
        SetEnvironmentVariableStmt n => [("Name", n.Name), ("Value", n.Value)],
        GetSystemFolderStmt n => [("FolderName", n.FolderName), ("Target", n.Target)],
        SetCurrentDirectoryStmt n => [("Path", n.Path)],
        XmlWriteFileStmt n => [("Xml", n.Xml), ("Path", n.Path)],
        XmlAddElementStmt n => [("Name", n.Name), ("Xml", n.Xml), ("Text", n.Text), ("Target", n.Target)],
        XmlRemoveElementStmt n => [("Element", n.Element)],
        XmlRemoveAttributeStmt n => [("Name", n.Name), ("Element", n.Element)],
        XmlSetTextStmt n => [("Element", n.Element), ("NameIn", n.NameIn), ("XmlIn", n.XmlIn), ("Value", n.Value)],
        XmlSetAttributeStmt n => [("Name", n.Name), ("Element", n.Element), ("Value", n.Value)],
        WriteBytesFileStmt n => [("Data", n.Data), ("Path", n.Path), ("Atomic", n.Atomic)],
        HashTextStmt n => [("Text", n.Text), ("Algorithm", n.Algorithm), ("Key", n.Key), ("ResultTarget", n.ResultTarget)],
        CipherTextStmt { Decrypt: true } n => [("CipherText", n.Text), ("Key", n.Key), ("ResultTarget", n.ResultTarget)],
        CipherTextStmt n => [("Text", n.Text), ("Key", n.Key), ("ResultTarget", n.ResultTarget)],
        GenerateKeyStmt n => [("Target", n.Target)],
        CryptoCipherStmt n => [("IsDecrypt", n.Decrypt), ("Data", n.Data), ("Key", n.Key), ("Target", n.Target)],
        HashPasswordStmt n => [("Password", n.Password), ("Target", n.Target)],
        ShowProgressStmt n => [("Percent", n.Percent)],
        ChooseFromListStmt n => [("Options", n.Options), ("Target", n.Target)],
        SetCursorStmt n => [("Row", n.Row), ("Column", n.Column)],
        WaitDelayStmt n => [("Duration", n.Duration), ("Unit", n.Unit)],
        StartTimerStmt n => [("Target", n.Target)],
        RunCommandStmt n => [("Target", n.Target), ("IsCommand", true), ("ResultTarget", n.ResultTarget)],
        RandomNumberStmt n => [("From", n.From), ("To", n.To), ("Target", n.Target)],
        RandomItemStmt n => [("Collection", n.Collection), ("Target", n.Target)],
        SetRandomSeedStmt n => [("Seed", n.Seed)],
        ReadJsonStmt n => [("Path", n.Path), ("Target", n.Target)],
        ConvertJsonStmt n => [("Subject", n.Subject), ("Target", n.Target)],
        ReadCsvStmt n => [("Path", n.Path), ("Target", n.Target)],
        WriteCsvStmt n => [("Rows", n.Rows), ("Path", n.Path)],
        ConvertCsvStmt n => [("Subject", n.Subject), ("Target", n.Target)],

        // UI (Syntax.Ui.cs)
        CreateUiResourceStmt n => [("TypeName", n.TypeName), ("Target", n.Target)],
        WhenStmt n => [("Target", n.Target), ("EventName", n.EventName), ("Body", n.Body)],
        PutInStmt n => [("Item", n.Item), ("Container", n.Container)],
        ShowStmt n => [("Target", n.Target)],
        ResponsiveRule n => [("Breakpoint", n.Breakpoint), ("Columns", n.Columns), ("Stack", n.Stack)],
        UiLayoutSpec n => [("Mode", n.Mode), ("Align", n.Align), ("Spread", n.Spread), ("Gap", n.Gap), ("Columns", n.Columns), ("Responsive", n.Responsive)],
        UiAnimationStep n => [("Operation", n.Operation), ("Direction", n.Direction), ("Amount", n.Amount)],
        UiAnimationBlock n => [("Trigger", n.Trigger), ("Steps", n.Steps), ("DurationMs", n.DurationMs), ("Easing", n.Easing)],
        UiEventStmt n => [("EventName", n.EventName), ("Body", n.Body)],
        UiElementStmt n => [("Tag", n.Tag), ("Variant", n.Variant), ("Label", n.Label), ("Name", n.Name), ("Layout", n.Layout),
                            ("Properties", n.Properties), ("Events", n.Events), ("Animations", n.Animations), ("Children", n.Children)],
        StateDefStmt n => [("Name", n.Name), ("InitialValue", n.InitialValue)],
        DeriveDefStmt n => [("Name", n.Name), ("Expression", n.Expression)],
        MemoDefStmt n => [("Name", n.Name), ("Body", n.Body)],
        WatchStmt n => [("TargetName", n.TargetName), ("Body", n.Body)],
        LifecycleStmt n => [("Stage", n.Stage), ("Body", n.Body)],
        SharedStateStmt n => [("Name", n.Name), ("InitialValue", n.InitialValue)],
        UiActionStmt n => [("Action", n.Action), ("Target", n.Target)],
        UseModuleStmt n => [("Module", n.Module)],
        RouteStmt n => [("Path", n.Path), ("IsOtherwise", n.IsOtherwise), ("PageName", n.PageName)],
        GoToRouteStmt n => [("Path", n.Path)],
        GoNavigateStmt n => [("IsForward", n.IsForward)],
        ReplaceRouteStmt n => [("Path", n.Path)],
        RouteChangeStmt n => [("Body", n.Body)],
        SetDragDataStmt n => [("Value", n.Value)],
        // System, network and data nodes (Otter.Contract.psm1's field order).
        BeginTransactionStmt n => [("Connection", n.Connection), ("Target", n.Target)],
        ChangedFileNameExpr or ChangedPathExpr or ChangeKindExpr or OldPathExpr or CloseCodeExpr or CloseReasonExpr or CloseWasCleanExpr
            or ReceivedMessageExpr or ReceivedResponseExpr or WebSocketErrorExpr => [],
        ChooseFileStmt n => [("Target", n.Target)],
        CommitTransactionStmt n => [("Transaction", n.Transaction)],
        RollbackTransactionStmt n => [("Transaction", n.Transaction)],
        ConnectDbStmt n => [("Config", n.Config), ("Target", n.Target)],
        DisconnectDbStmt n => [("Connection", n.Connection)],
        ConnectionIsSecureExpr n => [("Connection", n.Connection)],
        CopyToClipboardStmt n => [("Text", n.Text)],
        CreateSymbolicLinkStmt n => [("LinkPath", n.LinkPath), ("TargetPath", n.TargetPath)],
        DbExecuteStmt n => [("Connection", n.Connection), ("Command", n.Command), ("Parameters", n.Parameters), ("Target", n.Target)],
        DbQueryStmt n => [("Connection", n.Connection), ("Query", n.Query), ("Parameters", n.Parameters), ("Target", n.Target)],
        DeleteCredentialStmt n => [("Name", n.Name)],
        DeleteRegistryValueStmt n => [("ValueName", n.ValueName), ("KeyPath", n.KeyPath)],
        DeleteSecretStmt n => [("Name", n.Name)],
        DownloadFileStmt n => [("Url", n.Url), ("Path", n.Path)],
        FileIsReadOnlyExpr n => [("Path", n.Path)],
        FileIsSymbolicLinkExpr n => [("Path", n.Path)],
        FileWatchStmt n => [("TargetKind", n.TargetKind), ("Path", n.Path), ("Recursive", n.Recursive), ("Target", n.Target)],
        GetClipboardStmt n => [("Target", n.Target)],
        GetColumnsStmt n => [("Table", n.Table), ("Connection", n.Connection), ("Target", n.Target)],
        GetCredentialStmt n => [("Name", n.Name), ("Target", n.Target)],
        GetEventLogEntriesStmt n => [("LogName", n.LogName), ("MaxEntries", n.MaxEntries), ("Target", n.Target)],
        GetFileOwnerStmt n => [("Path", n.Path), ("Target", n.Target)],
        GetProcessesStmt n => [("Target", n.Target)],
        GetRegistryValueStmt n => [("ValueName", n.ValueName), ("KeyPath", n.KeyPath), ("Target", n.Target)],
        GetSymbolicLinkTargetStmt n => [("LinkPath", n.LinkPath), ("Target", n.Target)],
        GetSystemInfoStmt n => [("InfoKind", n.InfoKind), ("Target", n.Target)],
        GetTablesStmt n => [("Connection", n.Connection), ("Target", n.Target)],
        HttpCancelStmt n => [("Request", n.Request)],
        HttpDeleteStmt n => [("Url", n.Url), ("Target", n.Target), ("Options", n.Options)],
        HttpGetStmt n => [("Url", n.Url), ("Target", n.Target), ("AsJson", n.AsJson), ("Options", n.Options)],
        HttpSendStmt n => [("Data", n.Data), ("Url", n.Url), ("Target", n.Target), ("AsJson", n.AsJson), ("Options", n.Options)],
        HttpStartStmt n => [("Method", n.Method), ("Url", n.Url), ("Data", n.Data), ("AsJson", n.AsJson), ("TargetName", n.TargetName), ("Options", n.Options)],
        HttpRequestIsStateExpr n => [("Request", n.Request), ("ReqState", n.State)],
        IsWatchingExpr n => [("Watcher", n.Watcher)],
        JobContextExpr n => [("Field", n.Field)],
        NetContextExpr n => [("Field", n.Field)],
        KillProcessStmt n => [("ProcessExpr", n.Process), ("IncludeChildren", n.IncludeChildren)],
        ListenServerStmt n => [("Port", n.Port)],
        NetCloseStmt n => [("Protocol", n.Protocol), ("Socket", n.Socket)],
        NetworkEventStmt n => [("EventKind", n.EventKind), ("Socket", n.Socket), ("Body", n.Body)],
        NotifyStmt n => [("Title", n.Title), ("Message", n.Message)],
        PowerActionStmt n => [("Action", n.Action)],
        PrintFileStmt n => [("Path", n.Path), ("PrinterName", n.PrinterName)],
        QueryAggregateStmt n => [("AggregateFunc", n.AggregateFunction), ("Expression", n.Expression), ("Table", n.Table), ("Connection", n.Connection),
            ("Alias", n.Alias), ("Where", n.Where), ("Target", n.Target)],
        QueryBetweenExpr n => [("Expression", n.Expression), ("Lower", n.Lower), ("Upper", n.Upper)],
        QueryInExpr n => [("Expression", n.Expression), ("Collection", n.Collection), ("IsNot", n.IsNot)],
        QueryStmt n => [("IsDistinct", n.IsDistinct), ("Projections", n.Projections), ("Table", n.Table), ("Connection", n.Connection), ("Alias", n.Alias),
            ("Where", n.Where), ("OrderBy", n.OrderBy), ("Limit", n.Limit), ("Offset", n.Offset), ("Target", n.Target)],
        RegistryKeyExistsExpr n => [("KeyPath", n.KeyPath)],
        RespondStmt n => [("Value", n.Value), ("Status", n.Status), ("AsJson", n.AsJson)],
        RunProgramStmt n => [("Target", n.Target), ("IsCommand", false), ("ResultTarget", n.ResultTarget)],
        RunRemoteCommandStmt n => [("Command", n.Command), ("HostName", n.HostName), ("CredentialName", n.CredentialName), ("ResultTarget", n.ResultTarget)],
        RunSshCommandStmt n => [("Command", n.Command), ("HostName", n.HostName), ("ResultTarget", n.ResultTarget)],
        SecretExistsExpr n => [("Name", n.Name)],
        SecretReadExpr n => [("Name", n.Name)],
        SetCredentialStmt n => [("Name", n.Name), ("Secret", n.Secret)],
        SetFileReadOnlyStmt n => [("Path", n.Path), ("ReadOnly", n.ReadOnly)],
        SetProcessPriorityStmt n => [("ProcessExpr", n.Process), ("Priority", n.Priority)],
        SetRegistryValueStmt n => [("ValueName", n.ValueName), ("Value", n.Value), ("KeyPath", n.KeyPath)],
        StartCommandStmt n => [("CommandLine", n.CommandLine), ("Target", n.Target)],
        StartServerStmt n => [("Server", n.Target)],
        StopWatchingStmt n => [("Watcher", n.Watcher)],
        StoreSecretStmt n => [("Name", n.Name), ("Value", n.Value)],
        TcpConnectStmt n => [("HostExpr", n.HostExpr), ("Port", n.Port), ("Target", n.Target), ("IsSecure", n.IsSecure), ("ServerName", n.ServerName), ("Protocols", n.Protocols)],
