<#
.SYNOPSIS
Generates src/Otter.Cli/PowerShellSites.g.cs from otterPS 1.0.1's sources:
the lines of otter.ps1 and its modules that PowerShell quotes when it
reports an error there itself.

.DESCRIPTION
When a Write-Host fails (-InformationAction Stop or Ignore), or an error
escapes otter.ps1 (`otter serve` that cannot start, `otter desktop`'s import
problems and pages that cannot be written), powershell.exe prints the
statement's position: "At <file>:<line> char:<column>", the line, and "~"
under the statement (docs/SPEC-QUESTIONS.md C2-5, F5). The table keeps every
Write-Host line of otter.ps1 and of the modules whose Write-Host can fail
first, and the other statements PowerShell reports.

Run with PowerShell 7 or Windows PowerShell 5.1:

    pwsh -NoProfile -File tools/New-PowerShellSiteTable.ps1 -OtterPs ../otterPS-1.0.1
#>
param(
    [Parameter(Mandatory)][string]$OtterPs,
    [string]$OutFile = ''
)
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $PSScriptRoot
if (-not $OutFile) { $OutFile = Join-Path $here 'src/Otter.Cli/PowerShellSites.g.cs' }

# Every Write-Host of these files.
$writeHostFiles = @('otter.ps1', 'src\Otter.Profiler.psm1', 'src\Otter.Web.psm1', 'src\Otter.Desktop.psm1', 'src\Otter.Server.psm1', 'src\Otter.Project.psm1')
# Other statements PowerShell reports, as file = line numbers.
$statements = [ordered]@{
    'otter.ps1' = @(1021, 1035)
    'src\Otter.Module.psm1' = @(127, 128, 129, 130, 208, 218, 236, 242, 261)
    'src\Otter.Desktop.psm1' = @(1075, 1681)
    'src\Otter.Web.psm1' = @(3059)
    'src\Otter.Server.psm1' = @(282)
}

$entries = [System.Collections.Generic.SortedDictionary[string, string]]::new([System.StringComparer]::Ordinal)
foreach ($file in @($writeHostFiles + @($statements.Keys)) | Select-Object -Unique) {
    $lines = [System.IO.File]::ReadAllLines((Join-Path $OtterPs ($file -replace '\\', '/')))
    for ($i = 0; $i -lt $lines.Length; $i++) {
        $number = $i + 1
        $wanted = ($file -in $writeHostFiles -and $lines[$i] -match 'Write-Host') -or ($statements.Contains($file) -and $number -in $statements[$file])
        if ($wanted) { $entries["$($file):$number"] = $lines[$i].TrimEnd() }
    }
}

$out = [System.Text.StringBuilder]::new()
[void]$out.AppendLine('// <auto-generated> by tools/New-PowerShellSiteTable.ps1 from otterPS 1.0.1. Do not edit.')
[void]$out.AppendLine('namespace Otter.Cli;')
[void]$out.AppendLine('')
[void]$out.AppendLine('internal static partial class PowerShellSites')
[void]$out.AppendLine('{')
[void]$out.AppendLine('    // "<file>:<line>" (the file relative to otter.ps1''s folder) -> the line.')
[void]$out.AppendLine('    static readonly Dictionary<string, string> Lines = new(StringComparer.Ordinal)')
[void]$out.AppendLine('    {')
foreach ($key in $entries.Keys) {
    $text = $entries[$key].Replace('"', '""')
    [void]$out.AppendLine("        [@`"$($key.Replace('"', '""'))`"] = @`"$text`",")
}
[void]$out.AppendLine('    };')
[void]$out.AppendLine('}')
[System.IO.File]::WriteAllText($OutFile, $out.ToString().Replace("`r`n", "`n"), [System.Text.UTF8Encoding]::new($false))
Write-Host "$($entries.Count) lines -> $OutFile"
