<#
.SYNOPSIS
Generates src/Otter.Cli/AstDumpTable.g.cs from otterPS's Otter.Contract.psm1:
what otter.ps1's Show-OtterAst (-DebugAst) reads from each syntax node.

.DESCRIPTION
Show-OtterAst prints a node's Kind, then the first of its Name, Target,
VariableName and ResultTarget properties that holds something, and then
walks every other property in the order PowerShell lists them
($node.PSObject.Properties: the class's own properties first, then its base
class's), skipping Kind, Line, Name, Value, Target, VariableName and
ResultTarget. Only a property holding a node, an array, or an IfBranch can
print anything, so the table keeps, for every node class: its NodeKind, the
label properties it has, and its node-bearing properties in that order.

Run with PowerShell 7 or Windows PowerShell 5.1:

    pwsh -NoProfile -File tools/New-AstDumpTable.ps1 -OtterPs ../otterPS-1.0.1
#>
param(
    [Parameter(Mandatory)][string]$OtterPs,
    [string]$OutFile = ''
)
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $PSScriptRoot
if (-not $OutFile) { $OutFile = Join-Path $here 'src/Otter.Cli/AstDumpTable.g.cs' }
$contract = (Resolve-Path (Join-Path $OtterPs 'Otter.Contract.psm1')).Path

# Load the classes in a child scope: `using module` needs a literal path.
$script = @"
using module '$contract'
`$src = Get-Content -Raw -LiteralPath '$contract'
`$asm = [Node].Assembly
`$skip = @('Kind', 'Line', 'Name', 'Value', 'Target', 'VariableName', 'ResultTarget')
`$labels = @('Name', 'Target', 'VariableName', 'ResultTarget')
function Get-Kind([type]`$t) {
    `$m = [regex]::Match(`$src, "(?s)\nclass `$(`$t.Name) : (\w+) \{(.*?)\n\}")
    `$kinds = @([regex]::Matches(`$m.Groups[2].Value, 'base\(\[NodeKind\]::(\w+)') | ForEach-Object { `$_.Groups[1].Value } | Select-Object -Unique)
    if (`$kinds.Count -eq 1) { return `$kinds[0] }
    if (`$kinds.Count -eq 0 -and `$t.BaseType -ne [Node]) { return Get-Kind `$t.BaseType }
    throw "`$(`$t.Name): cannot tell its NodeKind"
}
foreach (`$t in (`$asm.GetTypes() | Where-Object { `$_.IsClass -and `$_.IsSubclassOf([Node]) } | Sort-Object Name)) {
    `$props = @(`$t.GetProperties() | Where-Object { -not `$_.GetGetMethod().IsStatic })
    `$label = @(`$labels | Where-Object { `$n = `$_; `$props | Where-Object { `$_.Name -eq `$n } })
    `$children = @(`$props | Where-Object { `$_.Name -notin `$skip } | Where-Object {
        `$pt = `$_.PropertyType
        `$pt -eq [object] -or `$pt -eq [Node] -or `$pt.IsSubclassOf([Node]) -or `$pt.Name -eq 'IfBranch[]' -or (`$pt.IsArray -and (`$pt.GetElementType() -eq [Node] -or `$pt.GetElementType().IsSubclassOf([Node]) -or `$pt.GetElementType() -eq [object]))
    } | ForEach-Object { `$_.Name })
    "`$(`$t.Name)|`$(Get-Kind `$t)|`$(`$label -join ',')|`$(`$children -join ',')"
}
"@
$temp = Join-Path ([System.IO.Path]::GetTempPath()) ('otter-ast-table-' + [Guid]::NewGuid().ToString('N') + '.ps1')
[System.IO.File]::WriteAllText($temp, $script)
try {
    $hostExe = if ($PSVersionTable.PSEdition -eq 'Core') { 'pwsh' } else { 'powershell.exe' }
    $rows = & $hostExe -NoProfile -File $temp
    if ($LASTEXITCODE -ne 0) { throw "reading the contract failed" }
}
finally { Remove-Item -LiteralPath $temp -Force -ErrorAction SilentlyContinue }

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('// <auto-generated> by tools/New-AstDumpTable.ps1 from otterPS 1.0.1''s Otter.Contract.psm1. Do not edit.')
$lines.Add('namespace Otter.Cli;')
$lines.Add('')
$lines.Add('internal static partial class AstDump')
$lines.Add('{')
$lines.Add('    // otterPS node class: NodeKind, label properties it has (Name, Target,')
$lines.Add('    // VariableName, ResultTarget), node-bearing properties in PSObject order.')
$lines.Add('    static readonly Dictionary<string, (string Kind, string[] Labels, string[] Children)> Table = new()')
$lines.Add('    {')
foreach ($row in $rows) {
    $name, $kind, $label, $children = $row -split '\|', 4
    $quote = { param($list) if (-not $list) { 'Array.Empty<string>()' } else { 'new[] { ' + ((($list -split ',') | ForEach-Object { '"' + $_ + '"' }) -join ', ') + ' }' } }
    $lines.Add("        [""$name""] = (""$kind"", $(& $quote $label), $(& $quote $children)),")
}
$lines.Add('    };')
$lines.Add('}')
[System.IO.File]::WriteAllText($OutFile, (($lines -join "`n") + "`n"), [System.Text.UTF8Encoding]::new($false))
Write-Host "$($rows.Count) node classes -> $OutFile"
