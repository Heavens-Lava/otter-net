<#
.SYNOPSIS
Regenerates src\Otter.Runtime\PowerShellCommands.cs from Windows PowerShell 5.1.

.DESCRIPTION
otterPS finds the program for `run command` with Get-Command, which returns a
PowerShell alias, function or cmdlet before any program on PATH - so
`run command "sort"` starts whatever `sort` resolves to after PowerShell's
own `sort` alias. otter-net reproduces that with this table: every built-in
alias, the functions PowerShell itself defines, and the cmdlets of the
modules that ship with Windows PowerShell (Microsoft.PowerShell.*). Commands
from optional modules differ from machine to machine and are left out.

Run with Windows PowerShell 5.1:
    powershell -NoProfile -File tools\New-PowerShellCommandTable.ps1
#>
$ErrorActionPreference = 'Stop'
if ($PSVersionTable.PSVersion.Major -ne 5) { throw 'Run this with Windows PowerShell 5.1 (powershell.exe).' }

$rows = [System.Collections.Generic.List[string]]::new()
foreach ($command in (Get-Command -CommandType Alias, Function, Cmdlet | Sort-Object Name -Unique)) {
    $kind = "$($command.CommandType)"
    $source = "$($command.Source)"
    $builtIn = switch ($kind) {
        'Alias' { $true }
        'Function' { $source -eq '' }
        'Cmdlet' { $source -like 'Microsoft.PowerShell.*' }
    }
    if (-not $builtIn) { continue }
    $name = $command.Name.Replace('\', '\\').Replace('"', '\"')
    $rows.Add("        [""$name""] = new(CommandKind.$kind, ""$source""),")
}

$lines = @(
    '// Generated by tools/New-PowerShellCommandTable.ps1 from Windows PowerShell 5.1.'
    '// Do not edit by hand.'
    'namespace Otter.Runtime;'
    ''
    'public enum CommandKind { Alias, Function, Cmdlet }'
    ''
    'public static class PowerShellCommands'
    '{'
    '    // Name (matched ignoring case, as Get-Command does) -> kind and Source.'
    '    public static readonly Dictionary<string, (CommandKind Kind, string Source)> BuiltIn = new(StringComparer.OrdinalIgnoreCase)'
    '    {'
) + $rows + @(
    '    };'
    '}'
)
$target = Join-Path (Split-Path -Parent $PSScriptRoot) 'src\Otter.Runtime\PowerShellCommands.cs'
[System.IO.File]::WriteAllText($target, ($lines -join "`n") + "`n", [System.Text.UTF8Encoding]::new($false))
Write-Host "$($rows.Count) commands written to $target"
